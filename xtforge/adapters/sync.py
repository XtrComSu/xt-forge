"""Sync xt-forge surfaces into a harness (single source of truth).

`adapters/opencode/commands/*.md`, `plugin/xt-native/` and
`adapters/generic/AGENTS.md.tpl` are the canon; this module copies them into
the live locations and reports exactly what changed. Idempotent: identical
files are reported as `unchanged`, nothing is ever deleted, and `--dry-run`
touches nothing.
"""
from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

from ..atomicio import atomic_write_text
from ..version import project_root, xt_home

SITE_PACKAGES_HINT = "lib/python3.*/site-packages"


def _site_packages(prefix: Path) -> Path | None:
    hits = sorted(prefix.glob(SITE_PACKAGES_HINT))
    return hits[-1] if hits else None


def _same(path: Path, text: str) -> bool:
    try:
        return path.read_text(encoding="utf-8") == text
    except (OSError, UnicodeDecodeError):
        return False


def _bash_for(prefix: Path) -> str:
    """Shebang for the generated scripts: Termux's bash when it is there."""
    candidate = prefix / "bin" / "bash"
    if candidate.exists():
        return str(candidate)
    for fallback in ("/usr/bin/bash", "/bin/bash", "/bin/sh"):
        if Path(fallback).exists():
            return fallback
    return "/bin/sh"


def _python_for(prefix: Path) -> Path:
    """The interpreter the generated scripts must use.

    The Termux prefix is the target, but a machine without it must not get a
    launcher that points at a path which does not exist.
    """
    candidate = prefix / "bin" / "python3"
    if candidate.exists():
        return candidate
    import sys
    return Path(sys.executable)


def _apply(actions: list[dict[str, Any]], path: Path, text: str,
           dry_run: bool, mode: int = 0o644) -> None:
    """Write `text` to `path` only when it differs (atomic, never deletes)."""
    entry: dict[str, Any] = {"path": str(path)}
    if _same(path, text):
        entry["action"] = "unchanged"
    elif dry_run:
        entry["action"] = "would_write"
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(path, text)
        os.chmod(path, mode)
        entry["action"] = "wrote"
    actions.append(entry)


LAUNCHER = """#!{bash}
# generated by `xtforge sync` — native-first dispatch, python fallback.
# XT_FORCE_PYTHON=1 forces the Python reference path. Absolute bash shebang:
# harness shells run with a stripped PATH where `env bash` cannot resolve.
ROOT="{root}"
export XT_HOME="${{XT_HOME:-{xt_home}}}"
export PYTHONPATH="{root}${{PYTHONPATH:+:$PYTHONPATH}}"
NATIVE="$ROOT/native/xtforge-rs/target/release/xtforge-native"
if [ "${{XT_FORCE_PYTHON:-0}}" != "1" ] && [ -x "$NATIVE" ]; then
  exec "$NATIVE" "$@"
fi
cd "$ROOT"
exec "{python}" -m xtforge.cli "$@"
"""


BOOT_HOOK = """#!{bash}
# xt-forge boot recalibration (installed by `xtforge sync`).
# Termux:Boot runs everything in ~/.termux/boot/ on device boot.
# Also safe to run by hand: `xtforge calibrate`.
set -u
ROOT="{root}"
export XT_HOME="${{XT_HOME:-{xt_home}}}"
export PYTHONPATH="{root}${{PYTHONPATH:+:$PYTHONPATH}}"
LOG="$XT_HOME/cache/boot-calibrate.log"
"{python}" -m xtforge.cli calibrate >>"$LOG" 2>&1 || true
"""


def opencode_commands() -> list[Path]:
    return sorted((project_root() / "adapters" / "opencode" / "commands").glob("*.md"))


def plugin_canon() -> Path:
    """Where the OpenCode plugin's source of truth lives."""
    from ..core.plugin import manager
    return manager.source_dir()


def plugin_install_dir(home: Path) -> Path:
    """Where the plugin is installed for the harness to load."""
    from ..core.plugin import manager
    return manager.target_dir(home)


def build_actions(dry_run: bool = False, home: Path | None = None,
                  prefix: Path | None = None) -> dict[str, Any]:
    """Compute (and unless dry_run, apply) every sync step."""
    home = home or Path(os.environ.get("HOME", str(Path.home())))
    prefix = prefix or Path(os.environ.get("XT_PREFIX", "/data/data/com.termux/files/usr"))
    # Captured before step 3 creates ~/.config/opencode/commands.
    opencode_present = (home / ".config" / "opencode").is_dir()
    root = project_root()
    actions: list[dict[str, Any]] = []

    # 1. pythonpath entry: makes `python3 -m xtforge.cli` work from any cwd,
    #    which is what every installed command template relies on.
    site = _site_packages(prefix)
    if site is None:
        actions.append({"path": str(prefix), "action": "skipped",
                        "reason": "no site-packages under XT_PREFIX"})
    else:
        _apply(actions, site / "xtforge.pth", f"{root}\n", dry_run)

    # 2. launcher on ~/bin
    python = _python_for(prefix)
    _apply(actions, home / "bin" / "xtforge",
           LAUNCHER.format(root=root, xt_home=xt_home(), python=python,
                         bash=_bash_for(prefix)),
           dry_run, mode=0o755)

    # 3. opencode command templates (canonical -> live)
    cmd_dir = home / ".config" / "opencode" / "commands"
    for src in opencode_commands():
        _apply(actions, cmd_dir / src.name, src.read_text(encoding="utf-8"), dry_run)

    # 3b. the OpenCode plugin: one installer, one canon.
    #     `xtforge plugin install` is the single writer; sync reports what it
    #     did so there is never a second way to install the plugin.
    actions.append(_plugin_install(home, dry_run))

    # 4. project-local command templates (keeps .opencode/ in step with canon)
    proj_dir = root / ".opencode" / "commands"
    for src in opencode_commands():
        _apply(actions, proj_dir / src.name, src.read_text(encoding="utf-8"), dry_run)

    # 5. themes (XT-Navigator and XT-Code, and anything added later)
    themes_dir = root / ".opencode" / "themes"
    live_themes = home / ".config" / "opencode" / "themes"
    for src in sorted(themes_dir.glob("*.json")):
        _apply(actions, live_themes / src.name, src.read_text(encoding="utf-8"), dry_run)

    # 6. AGENTS.md for shell-only harnesses
    from .generic_agents import TEMPLATE, render
    if TEMPLATE.is_file():
        _apply(actions, home / "AGENTS.md", render(home), dry_run)
    else:
        actions.append({"path": str(home / "AGENTS.md"), "action": "skipped",
                        "reason": "AGENTS.md template is missing from the repo"})

    # 7. opencode config wiring (additive only: never removes keys)
    actions.append(_config_wiring(home, dry_run, prefix, opencode_present))

    # 8. boot recalibration hook (Termux:Boot + manual).
    #    Without this, caps.json stays trusted for 1h across a reboot and
    #    mem.db-wal / flash TTLs are never cleaned until first manual use.
    boot_sh = home / ".termux" / "boot" / "xt-forge-calibrate.sh"
    _apply(actions, boot_sh,
           BOOT_HOOK.format(root=root, xt_home=xt_home(), python=python,
                          bash=_bash_for(prefix)),
           dry_run, mode=0o755)

    written = sum(1 for a in actions if a["action"] == "wrote")
    would = sum(1 for a in actions if a["action"] == "would_write")
    return {"ok": True, "dry_run": dry_run, "written": written,
            "would_write": would, "unchanged":
            sum(1 for a in actions if a["action"] == "unchanged"),
            "actions": actions}


def _has_jsonc_comments(text: str) -> bool:
    """True when // or /* appear outside of string literals."""
    in_str = False
    escaped = False
    i = 0
    while i < len(text):
        ch = text[i]
        if in_str:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
        elif ch == "/" and i + 1 < len(text) and text[i + 1] in "/*":
            return True
        i += 1
    return False


def _strip_jsonc_comments(text: str) -> str:
    """Drop // and /* */ comments outside string literals (parse-for-check only)."""
    out: list[str] = []
    in_str = False
    escaped = False
    i = 0
    while i < len(text):
        ch = text[i]
        if in_str:
            out.append(ch)
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == '"':
                in_str = False
        elif ch == '"':
            in_str = True
            out.append(ch)
        elif ch == "/" and i + 1 < len(text) and text[i + 1] == "/":
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        elif ch == "/" and i + 1 < len(text) and text[i + 1] == "*":
            i += 2
            while i + 1 < len(text) and not (text[i] == "*" and text[i + 1] == "/"):
                i += 1
            i += 2
            continue
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def _skip(entry: dict[str, Any], reason: str) -> dict[str, Any]:
    entry.update(action="skipped", reason=reason)
    return entry


def config_path(cfg_dir: Path) -> Path:
    """The config file OpenCode actually reads: `.json` first, then `.jsonc`."""
    for name in ("opencode.json", "opencode.jsonc"):
        candidate = cfg_dir / name
        if candidate.is_file():
            return candidate
    return cfg_dir / "opencode.json"


def _command_works(command: Any) -> bool:
    """True when an existing MCP command points at files that exist.

    A config that already runs xt-forge is left alone. Rewriting a working
    command with a path from another machine is how an installer breaks a
    working setup.
    """
    if not isinstance(command, list) or not command:
        return False
    exe, script = command[0], command[1] if len(command) > 1 else None
    if not (isinstance(exe, str) and Path(exe).exists()):
        return False
    if script and not Path(script).exists():
        return False
    return True


def _mcp_target(mcp: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """Where MCP servers live in this config, and whether it is the v2 shape.

    OpenCode v2 reads `mcp.servers.<name>`; the flat `mcp.<name>` form is the
    deprecated shape. The two accept different keys, so the shape decides
    what may be written.
    """
    servers = mcp.get("servers")
    if isinstance(servers, dict):
        return servers, True
    for key, value in mcp.items():
        if isinstance(value, dict) and ("command" in value or "url" in value):
            return mcp, False       # deprecated flat shape
    mcp["servers"] = {}
    return mcp["servers"], True


def _plugin_install(home: Path, dry_run: bool) -> dict[str, Any]:
    """Install the OpenCode plugin through its own manager.

    One writer: `xtforge plugin install` owns the plugin directory and the
    config registration. Sync asks it to do the work and reports the result.
    """
    from ..core.plugin import manager
    entry: dict[str, Any] = {"path": str(manager.target_dir(home))}
    try:
        before = manager.status(home=home)
        if dry_run:
            entry["action"] = "would_write" if not before.get("current") \
                else "unchanged"
            entry["files"] = sorted(manager.manifest())
            return entry
        res = manager.install(home=home)
        after = manager.status(home=home)
        changed = res.get("config_changed") or not before.get("current")
        entry.update(action="wrote" if changed else "unchanged",
                     files=res.get("files", []),
                     registered=res.get("registered"),
                     drift=after.get("drift"))
        return entry
    except (OSError, ValueError) as exc:
        return _skip(entry, f"plugin install failed: {exc}")


def _config_wiring(home: Path, dry_run: bool, prefix: Path,
                   opencode_present: bool = True) -> dict[str, Any]:
    """Ensure mcp.xt-forge is registered; report, never delete."""
    from ..core.plugin import manager
    cfg_dir = home / ".config" / "opencode"
    config = manager.config_path(home)
    entry: dict[str, Any] = {"path": str(config)}
    if not opencode_present or not cfg_dir.is_dir():
        return _skip(entry, "opencode config dir absent; opencode not installed")

    if config.is_file():
        try:
            raw = config.read_text(encoding="utf-8")
        except OSError as exc:
            return _skip(entry, f"unreadable config: {exc}")
        has_comments = _has_jsonc_comments(raw)
        parse_src = _strip_jsonc_comments(raw) if has_comments else raw
        try:
            start, end = parse_src.find("{"), parse_src.rfind("}")
            data = json.loads(parse_src[start:end + 1])
        except ValueError as exc:
            return _skip(entry, f"unparseable config: {exc}")
    else:
        raw, has_comments, data = "", False, {}

    root = str(project_root())
    changed = False
    mcp = data.setdefault("mcp", {})
    if not isinstance(mcp, dict):
        mcp = {}
        data["mcp"] = mcp
    servers, v2 = _mcp_target(mcp)
    server = servers.setdefault("xt-forge", {})
    # Only fill in what is missing or broken: a config that already runs
    # xt-forge keeps its own command.
    if not _command_works(server.get("command")):
        python = _python_for(prefix)
        server["type"] = "local"
        server["command"] = [str(python), str(project_root() / "adapters" /
                                              "mcp" / "server.py")]
        server["cwd"] = root
        changed = True
    if "environment" not in server:
        server["environment"] = {"XT_HOME": str(xt_home())}
        changed = True
    if not v2:
        # The deprecated shape accepts "enabled" and an integer timeout; the
        # v2 shape uses "disabled" and an object timeout, so nothing is
        # written there that the schema would reject.
        for key, value in (("enabled", True), ("timeout", 30000)):
            if key not in server:
                server[key] = value
                changed = True

    if not changed:
        entry.update(action="unchanged")
        return entry
    if has_comments:
        return _skip(entry, "config carries comments; merge mcp/plugin keys by hand")
    if dry_run:
        entry.update(action="would_write")
        return entry
    atomic_write_text(config, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    entry.update(action="wrote")
    return entry
