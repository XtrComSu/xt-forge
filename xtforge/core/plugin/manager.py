"""Install, check and remove the OpenCode plugin that ships with xt-forge.

The plugin used to live only in `~/.config/opencode/plugins/xt-native/`, as a
loose file nobody could review. It is source in this repository now, and this
module is what puts it on a machine:

    xtforge plugin install     # copy the source, register it, stamp the paths
    xtforge plugin status      # is it installed, registered, and current?
    xtforge plugin uninstall   # unregister it (files only with --purge)

Every step is idempotent and reports what it changed, so installing twice is
a no-op and a half-finished install can be finished by running it again.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import time
from pathlib import Path

PLUGIN_ID = "xt-native"
# The canon: the plugin source lives in the repository, under `plugins/`.
SOURCE_REL = Path("plugins") / PLUGIN_ID
# The files that make up the running plugin. Tests are not installed: the
# live copy only has to load, not to prove itself.
PAYLOAD = ("index.ts", "package.json")
STAMP_NAME = "installed.json"
MANIFEST_NAME = "installed.json"
# Generated by the installer; never part of the shipped source.
GENERATED = {STAMP_NAME}


def repo_root() -> Path:
    """The xt-forge checkout this module lives in."""
    return Path(__file__).resolve().parents[3]


def source_dir(root: Path | None = None) -> Path:
    return (root or repo_root()) / SOURCE_REL


def home_dir() -> Path:
    return Path(os.environ.get("HOME", str(Path.home())))


def target_dir(home: Path | None = None) -> Path:
    return (home or home_dir()) / ".config" / "opencode" / "plugins" / PLUGIN_ID


def config_path(home: Path | None = None) -> Path:
    """The OpenCode config to register the plugin in (json or jsonc)."""
    base = (home or home_dir()) / ".config" / "opencode"
    for name in ("opencode.json", "opencode.jsonc"):
        candidate = base / name
        if candidate.is_file():
            return candidate
    return base / "opencode.json"


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def manifest(root: Path | None = None) -> dict[str, str]:
    """sha256 of every shipped file, keyed by path relative to the source."""
    src = source_dir(root)
    out: dict[str, str] = {}
    for name in PAYLOAD:
        path = src / name
        if path.is_file():
            out[name] = _sha256(path)
    return out


def _read_config(path: Path) -> tuple[dict, bool]:
    """Read a config file. Returns (data, is_jsonc)."""
    if not path.is_file():
        return {}, False
    text = path.read_text(encoding="utf-8")
    try:
        return json.loads(text), False
    except ValueError:
        start, end = text.find("{"), text.rfind("}")
        if start < 0 or end <= start:
            raise ValueError(f"{path} is not valid JSON or JSONC")
        return json.loads(text[start:end + 1]), True


def _write_config(path: Path, data: dict, is_jsonc: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_file():
        backup = path.with_name(path.name + f".bak-{int(time.time())}")
        shutil.copy2(path, backup)
    text = json.dumps(data, indent=2, ensure_ascii=False) + "\n"
    path.write_text(text, encoding="utf-8")


def _registered_entries(data: dict) -> list:
    plugins = data.get("plugins")
    if isinstance(plugins, list):
        return plugins
    if isinstance(plugins, str):
        return [plugins]
    return []


def _entry_path(entry) -> str | None:
    if isinstance(entry, str):
        return entry
    if isinstance(entry, dict) and isinstance(entry.get("package"), str):
        return entry["package"]
    return None


def register(config: Path, plugin_path: Path) -> dict:
    """Add the plugin to the config's `plugins` list, preserving everything else."""
    data, is_jsonc = _read_config(config)
    wanted = str(plugin_path)
    entries = _registered_entries(data)
    for entry in entries:
        if _entry_path(entry) == wanted:
            return {"registered": True, "changed": False, "config": str(config)}
    entries.append(wanted)
    data["plugins"] = entries
    _write_config(config, data, is_jsonc)
    return {"registered": True, "changed": True, "config": str(config)}


def unregister(config: Path, plugin_path: Path) -> dict:
    """Remove the plugin from the config's `plugins` list."""
    if not config.is_file():
        return {"registered": False, "changed": False, "config": str(config)}
    data, is_jsonc = _read_config(config)
    wanted = str(plugin_path)
    entries = _registered_entries(data)
    kept = [e for e in entries if _entry_path(e) != wanted]
    if len(kept) == len(entries):
        return {"registered": False, "changed": False, "config": str(config)}
    data["plugins"] = kept
    _write_config(config, data, is_jsonc)
    return {"registered": False, "changed": True, "config": str(config)}


def _stamp(root: Path | None, python: str | None) -> dict:
    from ...version import version, xt_home
    return {
        "plugin": PLUGIN_ID,
        "version": version(),
        "root": str(root or repo_root()),
        "python": python or shutil.which("python3") or "python3",
        "xt_home": str(xt_home()),
        "files": manifest(root),
    }


def install(home: Path | None = None, target: Path | None = None,
            root: Path | None = None, python: str | None = None) -> dict:
    """Copy the plugin source, stamp it, and register it with OpenCode."""
    src = source_dir(root)
    if not src.is_dir():
        raise FileNotFoundError(f"plugin source not found: {src}")
    dst = Path(target) if target else target_dir(home)
    dst.mkdir(parents=True, exist_ok=True)

    copied: list[str] = []
    for name in PAYLOAD:
        path = src / name
        if not path.is_file():
            continue
        out = dst / name
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, out)
        copied.append(name)

    # Stale files from an older layout are removed, so the installed plugin
    # is exactly the repo plugin and not a union of two versions.
    removed: list[str] = []
    for item in sorted(dst.iterdir()):
        if item.name in PAYLOAD or item.name in GENERATED or item.is_dir():
            continue
        item.unlink()
        removed.append(item.name)

    stamp = _stamp(root, python)
    stamp["installed_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    (dst / STAMP_NAME).write_text(
        json.dumps(stamp, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    reg = register(config_path(home), dst)
    return {
        "ok": True,
        "target": str(dst),
        "files": copied,
        "removed": removed,
        "registered": reg["registered"],
        "config_changed": reg["changed"],
        "config": reg["config"],
        "version": stamp["version"],
        "root": stamp["root"],
        "python": stamp["python"],
    }


def status(home: Path | None = None, target: Path | None = None,
           root: Path | None = None) -> dict:
    """Is the plugin installed, registered, and the same as the source?"""
    dst = Path(target) if target else target_dir(home)
    cfg = config_path(home)
    out: dict[str, object] = {
        "plugin": PLUGIN_ID,
        "target": str(dst),
        "config": str(cfg),
        "installed": (dst / "index.ts").is_file(),
        "registered": False,
        "current": False,
        "version": None,
        "root": None,
        "python": None,
        "drift": {"missing": [], "modified": [], "extra": []},
    }
    if not out["installed"]:
        return out

    stamp_file = dst / STAMP_NAME
    stamp = {}
    if stamp_file.is_file():
        try:
            stamp = json.loads(stamp_file.read_text(encoding="utf-8"))
        except ValueError:
            stamp = {}
    out["version"] = stamp.get("version")
    out["root"] = stamp.get("root")
    out["python"] = stamp.get("python")

    try:
        data, _ = _read_config(cfg)
        out["registered"] = any(_entry_path(e) == str(dst)
                                for e in _registered_entries(data))
    except ValueError:
        out["registered"] = False

    want = manifest(root) if source_dir(root).is_dir() else stamp.get("files", {})
    have = {}
    for name in PAYLOAD:
        path = dst / name
        if path.is_file():
            have[name] = _sha256(path)
    extra = [item.name for item in sorted(dst.iterdir())
             if item.is_file() and item.name not in PAYLOAD
             and item.name not in GENERATED]
    drift = out["drift"]
    for rel, digest in want.items():
        if rel not in have:
            drift["missing"].append(rel)
        elif have[rel] != digest:
            drift["modified"].append(rel)
    drift["extra"] = extra
    out["current"] = not any(drift.values())
    return out


def uninstall(home: Path | None = None, target: Path | None = None,
              purge: bool = False) -> dict:
    """Unregister the plugin. `purge` also removes the installed files."""
    dst = Path(target) if target else target_dir(home)
    reg = unregister(config_path(home), dst)
    removed = False
    if purge and dst.is_dir():
        shutil.rmtree(dst)
        removed = True
    return {
        "ok": True,
        "target": str(dst),
        "registered": reg["registered"],
        "config_changed": reg["changed"],
        "files_removed": removed,
    }
