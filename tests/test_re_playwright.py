"""Tests for the Playwright trace reader.

The fixture is a real trace: generated by Playwright's own `tracing.start()` against
the bundled Chromium, then read back. That matters because a trace is not a documented
byte format — it is whatever Playwright writes — so a reader validated only against a
hand-built zip would be validating my assumptions, not the format.

Three traps, each with a test that fails when the guard is removed:

  * A trace member is **newline-delimited JSON**, not a JSON array. `json.load` on a
    valid trace raises, so the reader must split by line.
  * Event times are **offsets in milliseconds**, not wall-clock. Rendering them as
    dates invents timestamps.
  * A failed action records an `error` key; success simply omits it. A missing key is
    the success case, not missing data.
"""
from __future__ import annotations

import json
import shutil
import subprocess
import tempfile
import unittest
import zipfile
from pathlib import Path

from xtforge.core.re import playwright


def _find_playwright() -> tuple[str, str] | tuple[None, None]:
    """Locate a node binary and a resolvable playwright module."""
    node = shutil.which("node")
    if node is None:
        return None, None
    candidates = [
        shutil.which("playwright"),
        str(Path.home() / ".npm" / "_npx"),
    ]
    # Search the npx cache, which is where a `npx playwright` install lands.
    for root in candidates:
        if not root:
            continue
        base = Path(root)
        if base.is_file():
            base = base.parent
        for match in sorted(base.rglob("node_modules/playwright"))[:3]:
            return node, str(match)
    return node, None


def build_trace(directory: Path, *, fail: bool) -> Path | None:
    """Generate a real Playwright trace. None when node/playwright are unavailable."""
    node, module = _find_playwright()
    if node is None or module is None:
        return None
    target = directory / ("fail.zip" if fail else "ok.zip")
    action = ("await page.click('#does-not-exist', { timeout: 900 })"
              if fail else "await page.click('h1')")
    script = directory / "drive.js"
    script.write_text(f"""
const {{ chromium }} = require({module!r});
(async () => {{
  const browser = await chromium.launch();
  const context = await browser.newContext();
  await context.tracing.start({{ snapshots: true }});
  const page = await context.newPage();
  await page.goto('data:text/html,<title>XtForgeTrace</title><h1>hello</h1>');
  try {{ {action}; }} catch (e) {{ /* asserted by the test, not a script failure */ }}
  await context.tracing.stop({{ path: {str(target)!r} }});
  await browser.close();
}})();
""")
    result = subprocess.run([node, str(script)], capture_output=True, text=True,
                            timeout=180)
    if result.returncode != 0 or not target.is_file():
        return None
    return target


def synthetic_trace(directory: Path, lines: list[dict], *,
                    name: str = "synthetic.zip") -> Path:
    """A minimal trace with exactly the events a test needs."""
    target = directory / name
    with zipfile.ZipFile(target, "w") as archive:
        archive.writestr("trace.trace",
                         "\n".join(json.dumps(line) for line in lines) + "\n")
        archive.writestr("trace.network", "")
    return target


class RealTraceTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls._tmp = tempfile.TemporaryDirectory()
        cls.root = Path(cls._tmp.name)
        cls.ok = build_trace(cls.root, fail=False)
        cls.failed = build_trace(cls.root, fail=True)

    @classmethod
    def tearDownClass(cls) -> None:
        cls._tmp.cleanup()

    def setUp(self) -> None:
        if self.ok is None:
            self.skipTest("node + playwright unavailable to generate a real trace")

    def test_header_identifies_the_trace(self) -> None:
        report = playwright.inspect_playwright_trace(self.ok)
        self.assertTrue(report["ok"], report.get("error"))
        self.assertEqual(report["kind"], "playwright-trace")
        self.assertIsInstance(report["version"], int)
        self.assertEqual(report["browser"], "chromium")

    def test_actions_are_paired_with_durations(self) -> None:
        """`before` opens an action and `after` closes it.

        Only pairing the two yields a duration; reading either alone gives a list of
        start times with no idea what finished, or when.
        """
        report = playwright.inspect_playwright_trace(self.ok)
        apis = [action["api"] for action in report["actions"]]
        self.assertIn("Frame.goto", apis)
        self.assertIn("Frame.click", apis)
        for action in report["actions"]:
            self.assertIn("duration_ms", action, action)
            self.assertGreaterEqual(action["duration_ms"], 0)

    def test_successful_trace_has_no_failures(self) -> None:
        report = playwright.inspect_playwright_trace(self.ok)
        self.assertEqual(report["failure_count"], 0)

    def test_failed_action_is_reported_with_its_message(self) -> None:
        """A missing `error` key is the success case; its presence means failure."""
        if self.failed is None:
            self.skipTest("failing trace could not be generated")
        report = playwright.inspect_playwright_trace(self.failed)
        self.assertEqual(report["failure_count"], 1)
        failure = report["failures"][0]
        self.assertEqual(failure["api"], "Frame.click")
        self.assertIn("Timeout", failure["message"])

    def test_duration_is_an_offset_not_a_date(self) -> None:
        """Times are milliseconds from trace start.

        A trace lasting under a second must report a small duration. Rendering the
        offsets as epochs would produce a duration near 1.7e12 and a 1970 date.
        """
        report = playwright.inspect_playwright_trace(self.ok)
        self.assertIsNotNone(report["duration_ms"])
        self.assertLess(report["duration_ms"], 600_000)
        self.assertGreater(report["duration_ms"], 0)

    def test_console_and_snapshots_are_counted(self) -> None:
        report = playwright.inspect_playwright_trace(self.ok)
        self.assertGreater(report["event_count"], 0)
        self.assertGreater(report["snapshot_count"], 0)
        self.assertIn("frame-snapshot", report["event_kinds"])


class TraceFormatTest(unittest.TestCase):
    """Format assertions on synthetic traces, so they do not depend on Playwright."""

    def test_jsonl_is_parsed_line_by_line(self) -> None:
        """A trace is JSONL.

        `json.load` on the whole member raises "Extra data" on a perfectly valid
        trace, so the reader must parse one line at a time.
        """
        lines = [
            {"version": 8, "type": "context-options", "browserName": "chromium"},
            {"type": "before", "callId": "c1", "class": "Page", "method": "goto",
             "startTime": 10.0, "params": {"url": "https://example.test/"}},
            {"type": "after", "callId": "c1", "endTime": 42.5},
        ]
        with tempfile.TemporaryDirectory() as tmp:
            path = synthetic_trace(Path(tmp), lines)
            report = playwright.inspect_playwright_trace(path)
        self.assertTrue(report["ok"], report.get("error"))
        self.assertEqual(report["event_count"], 3)
        self.assertEqual(report["unparsed_lines"], 0)
        self.assertEqual(report["action_count"], 1)
        self.assertEqual(report["actions"][0]["url"], "https://example.test/")
        self.assertAlmostEqual(report["actions"][0]["duration_ms"], 32.5, places=3)

    def test_partial_final_line_is_dropped_not_raised(self) -> None:
        """A trace cut off mid-write leaves a broken last line."""
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "truncated.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("trace.trace",
                                 '{"type":"before","callId":"c1","method":"click"}\n'
                                 '{"type":"after","callId":"c1","endTi')
            report = playwright.inspect_playwright_trace(target)
        self.assertTrue(report["ok"], report.get("error"))
        self.assertEqual(report["event_count"], 1)
        self.assertEqual(report["unparsed_lines"], 1)

    def test_network_member_is_read(self) -> None:
        network = [
            {"type": "resource-snapshot",
             "snapshot": {"request": {"url": "https://example.test/app.js",
                                      "method": "GET"},
                          "response": {"status": 200},
                          "resourceType": "script"}},
            {"type": "resource-snapshot",
             "snapshot": {"request": {"url": "https://example.test/missing",
                                      "method": "GET"},
                          "response": {"status": 404},
                          "resourceType": "fetch"}},
        ]
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "with-network.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("trace.trace",
                                 '{"type":"context-options","version":8}\n')
                archive.writestr("trace.network",
                                 "\n".join(json.dumps(entry) for entry in network))
            report = playwright.inspect_playwright_trace(target)
        self.assertEqual(report["network_count"], 2)
        statuses = {entry["url"]: entry["status"] for entry in report["network"]}
        self.assertEqual(statuses["https://example.test/app.js"], 200)
        self.assertEqual(statuses["https://example.test/missing"], 404)

    def test_screenshots_are_listed(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "shots.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("trace.trace", '{"type":"context-options"}\n')
                archive.writestr("abc123.jpeg", b"\xff\xd8\xff")
                archive.writestr("def456.png", b"\x89PNG")
            report = playwright.inspect_playwright_trace(target)
        self.assertEqual(report["screenshot_count"], 2)
        self.assertIn("abc123.jpeg", report["screenshots"])


class TraceBoundariesTest(unittest.TestCase):
    def test_zip_without_trace_member_is_rejected(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "other.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("readme.txt", "not a trace")
            report = playwright.inspect_playwright_trace(target)
        self.assertFalse(report["ok"])
        self.assertIn("trace.trace", report["error"])

    def test_non_zip_is_rejected(self) -> None:
        report = playwright.inspect_playwright_trace("/bin/ls")
        self.assertFalse(report["ok"])
        self.assertIn("not a zip", report["error"])

    def test_missing_file_reports_error(self) -> None:
        report = playwright.inspect_playwright_trace("/nonexistent/trace.zip")
        self.assertFalse(report["ok"])
        self.assertIn("error", report)

    def test_empty_trace_member_is_ok_with_zero_events(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "empty.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("trace.trace", "")
            report = playwright.inspect_playwright_trace(target)
        self.assertTrue(report["ok"], report.get("error"))
        self.assertEqual(report["event_count"], 0)
        self.assertEqual(report["action_count"], 0)

    def test_malformed_lines_never_raise(self) -> None:
        lines = ['{"type":', 'not json at all', '{"type":"before"}',
                 '[1,2,3]', '{"type":"after","callId":"ghost"}']
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "garbage.zip"
            with zipfile.ZipFile(target, "w") as archive:
                archive.writestr("trace.trace", "\n".join(lines))
            report = playwright.inspect_playwright_trace(target)
        self.assertTrue(report["ok"], report.get("error"))
        # Two of the five lines are valid objects; the JSON array is not an object.
        self.assertEqual(report["event_count"], 2)
        self.assertEqual(report["unparsed_lines"], 3)


if __name__ == "__main__":
    unittest.main()
