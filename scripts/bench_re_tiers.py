#!/usr/bin/env python3
"""Tiered reverse-engineering benchmark: 15 difficulty tiers x 3 formats x N repetitions.

Each tier is a question with an answer the tool must produce, checked against an
independent oracle where one exists (llvm-readelf/objdump/nm, or arithmetic recomputed
here). Repetitions give a median, because a single run of a subprocess pipeline measures
the page cache as much as the tool.

    python scripts/bench_re_tiers.py --reps 5 --json /tmp/bench.json

Tiers are ordered by what an analyst needs first: know what the file is, then find code,
then read code, then explain it. A tier that fails is reported as failing — the point is a
measurement, not a score.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import shutil
import statistics
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HUB = ROOT / "native" / "xtforge-go" / "xtforge-hub"

# One representative corpus per format, all real artefacts present on this machine.
CORPUS = {
    "elf": [
        "/tmp/dy",                                   # small PIE executable, symbols present
        "/usr/bin/opencode",                         # 81 MB, no .eh_frame, stripped-ish
        "/usr/lib/libgfortran.so.5.0.0",             # large shared object with .eh_frame
    ],
    "pe": [
        "/usr/lib/wine/x86_64-windows/kernel32.dll",
        "/usr/lib/wine/i386-windows/kernel32.dll",   # real 32-bit PE
        "/usr/lib/wine/x86_64-windows/kernelbase.dll",
    ],
    # PDB fixtures are generated by the Go tests (clang-cl + lld-link); the paths below are
    # where those tests leave them, and the tier skips when they are absent.
    "pdb": [
        "/tmp/pdbt/t.pdb",
        "/tmp/pdbt/arr.pdb",
    ],
    "macho": [
        "/tmp/dmgtest/Delta Installer.app/Contents/MacOS/Delta Installer",
        "/tmp/mo.bin",
    ],
}


def hub(*args: str, timeout: int = 300) -> dict:
    completed = subprocess.run([str(HUB), "re", *args, "--json"], capture_output=True,
                               text=True, timeout=timeout)
    try:
        return json.loads(completed.stdout or "{}")
    except ValueError:
        return {"ok": False, "error": (completed.stdout + completed.stderr)[:200]}


def first_image(payload: dict) -> dict:
    images = payload.get("images") or []
    return images[0] if images else {}


def arch_of(path: str) -> str:
    """The slice to analyse. A universal binary needs one named explicitly, and the engine
    is right to refuse rather than guess: without this every Mach-O tier failed on
    "more than one matching slice" — a harness defect that looked like a product defect."""
    payload = hub("overview", path)
    images = payload.get("images") or []
    if len(images) <= 1:
        return images[0].get("arch", "") if images else ""
    best, best_count = "", -1
    for image in images:
        count = len(image.get("functions") or [])
        if count > best_count:
            best, best_count = image.get("arch", ""), count
    return best


def with_arch(path: str) -> list[str]:
    arch = arch_of(path)
    return ["--arch", arch] if arch else []


def available(paths: list[str]) -> list[str]:
    return [p for p in paths if Path(p).exists()]


# --- tiers -----------------------------------------------------------------------------
# Each tier returns (passed, detail). Tiers that cannot apply to a format return
# ("skip", reason) and are reported separately rather than counted as passes.


def tier1_format(path: str, expected: str):
    if expected == "pdb":
        return "skip", "a PDB is exercised by T13 (types), not by format detection"
    payload = hub("overview", path)
    got = payload.get("format")
    ok = payload.get("ok") and got in (expected, {"macho": "mach-o"}.get(expected, expected))
    return ok, f"format={got}"


def tier2_arch(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    image = first_image(hub("overview", path))
    arch, bits = image.get("arch"), image.get("bits")
    return bool(arch and bits), f"arch={arch} bits={bits}"


def tier3_entry(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    image = first_image(hub("overview", path))
    entry = image.get("entry_point")
    if entry is None:
        # A shared object or dylib legitimately has no entry point, so the anchor is the
        # first recovered function. Scoring that as a failure would punish correct output.
        payload = hub("functions", path, "--limit", "1")
        functions = first_image(payload).get("functions") or []
        return bool(functions), f"no entry; first function={functions[0]['address'] if functions else None}"
    return isinstance(entry, int) and entry > 0, f"entry={entry}"


def tier4_sections(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    sections = first_image(hub("overview", path)).get("sections") or []
    if expected == "elf" and shutil.which("llvm-readelf"):
        out = subprocess.run(["llvm-readelf", "-S", path], capture_output=True, text=True).stdout
        oracle = len([l for l in out.splitlines() if "]" in l and l.strip().startswith("[")])
        return abs(len(sections) - oracle) <= 1, f"sections={len(sections)} oracle={oracle}"
    return len(sections) > 0, f"sections={len(sections)}"


def tier5_names(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    # --limit 50 returns the 50 lowest addresses, which on a stripped binary are heuristic
    # call targets; the symbols sit further up. Sample the whole index instead.
    payload = hub("functions", path, "--limit", "100000")
    functions = first_image(payload).get("functions") or []
    named = [f for f in functions if f.get("name")]
    if named:
        return True, f"named={len(named)}/{len(functions)}"
    # A stripped binary has no names to recover. The question is then whether the engine
    # also reports no symbols — if it invented names there would be something to catch.
    if shutil.which("llvm-nm"):
        out = subprocess.run(["llvm-nm", "--defined-only", path], capture_output=True,
                             text=True).stdout
        oracle = [l for l in out.splitlines() if " T " in l or " t " in l]
        if not oracle:
            return True, "no names, and llvm-nm finds no symbols either"
        return False, f"named=0 but llvm-nm reports {len(oracle)} defined text symbols"
    return True, "named=0 (no symbol oracle available)"


def code_function(path: str, expected: str) -> tuple[int | None, str]:
    """First indexed function that is actually code.

    A Mach-O index starts with __mh_execute_header, the address of the mach header itself —
    real, but not a function. Disassembling it decodes nothing, which the harness used to
    report as a product failure.
    """
    payload = hub("functions", path, "--limit", "200")
    for function in first_image(payload).get("functions") or []:
        name = function.get("name") or ""
        if name in ("__mh_execute_header", "_mh_execute_header"):
            continue
        return function["address"], name
    return None, ""


def tier6_disasm(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    address, _ = code_function(path, expected)
    if address is None:
        return False, "no function to disassemble"
    decoded = hub("disasm-native", path, "--target", hex(address), "--max-instructions", "8",
                  *with_arch(path))
    instructions = decoded.get("instructions") or []
    opaque = sum(1 for i in instructions if i.get("mnemonic") == "opaque")
    return decoded.get("ok") and len(instructions) >= 4 and opaque == 0, \
        f"decoded={len(instructions)} opaque={opaque}"


def tier7_xrefs(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    payload = hub("xrefs-native", path, "--limit", "200", "--max-functions", "256",
                  *with_arch(path))
    references = payload.get("references") or []
    named = [r for r in references if r.get("target_name")]
    return payload.get("ok") and len(references) > 0, \
        f"refs={len(references)} named={len(named)}"


def tier8_imports(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    image = first_image(hub("overview", path))
    imports = image.get("imports") or []
    exports = image.get("exports") or []
    total = len(imports) + len(exports)
    if expected == "macho":
        dependencies = len(image.get("dependencies") or [])
        if dependencies == 0 and not imports and not exports:
            return "skip", "freestanding image: links and exports nothing"
        return dependencies > 0 or total > 0, f"dependencies={dependencies}"
    return total > 0, f"imports={len(imports)} exports={len(exports)}"


def tier9_strings(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    payload = hub("strings", path, "--limit", "20", "--min-len", "6") \
        if False else None  # strings is a CLI verb, not a hub verb; use the CLI surface
    completed = subprocess.run([sys.executable, "-m", "xtforge.cli", "re", "strings", path,
                                "--limit", "20", "--min-len", "6", "--json"],
                               capture_output=True, text=True, cwd=str(ROOT), timeout=180)
    try:
        data = json.loads(completed.stdout)
    except ValueError:
        return False, "strings did not return JSON"
    found = data.get("strings") or []
    return data.get("ok") and len(found) > 0, f"strings={len(found)}"


def tier10_entropy(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    completed = subprocess.run([sys.executable, "-m", "xtforge.cli", "re", "entropy", path,
                                "--json"], capture_output=True, text=True, cwd=str(ROOT),
                               timeout=180)
    try:
        reported = json.loads(completed.stdout).get("entropy")
    except ValueError:
        return False, "entropy did not return JSON"
    data = Path(path).read_bytes()  # whole file: a 4 MB prefix disagreed with an 81 MB binary
    counts = Counter(data)
    total = len(data)
    oracle = -sum(c / total * math.log2(c / total) for c in counts.values())
    return reported is not None and abs(reported - oracle) < 0.01, \
        f"reported={reported:.4f} oracle={oracle:.4f}"


def tier11_callgraph(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    arch = arch_of(path)
    argv = [sys.executable, "-m", "xtforge.cli", "re", "callgraph", path, "--json"]
    if arch:
        argv += ["--arch", arch]
    completed = subprocess.run(argv, capture_output=True, text=True, cwd=str(ROOT),
                               timeout=240)
    try:
        data = json.loads(completed.stdout)
    except ValueError:
        return False, "callgraph did not return JSON"
    edges = data.get("edges") or 0
    return data.get("ok") and edges > 0, f"edges={edges} nodes={data.get('nodes')}"


def tier12_decompile(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    address, _ = code_function(path, expected)
    if address is None:
        return False, "no function to decompile"
    result = hub("decompile-native", path, "--target", hex(address),
                 *with_arch(path))
    coverage = result.get("coverage") or {}
    return result.get("ok") and coverage.get("decoded", 0) > 0, \
        f"decoded={coverage.get('decoded')} lifted={coverage.get('lifted')}"


def tier13_types(path: str, expected: str):
    if expected == "pdb":
        payload = hub("pdb-types", path)
        aggregates = payload.get("aggregates") or []
        signatures = payload.get("signatures") or []
        named = [s for s in signatures if s.get("parameters")]
        return payload.get("ok") and len(aggregates) > 0, \
            f"aggregates={len(aggregates)} signatures={len(signatures)} named_args={len(named)}"
    if expected != "pe":
        return "skip", "type information is a PE/PDB surface"
    pdb = Path(path).with_suffix(".pdb")
    if not pdb.exists():
        return "skip", "no PDB beside this binary"
    payload = hub("pdb-types", str(pdb))
    aggregates = payload.get("aggregates") or []
    return payload.get("ok") and len(aggregates) > 0, f"aggregates={len(aggregates)}"


_DENSE_SWITCH_SOURCE = """\
__attribute__((noinline)) int dense(int op, int x) {
    switch (op) {
    case 0: return x + 3;
    case 1: return x + 10;
    case 2: return x + 17;
    case 3: return x + 24;
    case 4: return x + 31;
    case 5: return x + 38;
    case 6: return x + 45;
    case 7: return x + 52;
    default: return x;
    }
}
int main(void) { return dense(3, 5) - 24; }
"""


def dense_switch_fixture() -> str | None:
    """Build the dense-switch binary, or return None if no compiler is available.

    Tier 14 used to read a hard-coded /tmp/densebin and skip when it was absent, so
    the tier reported nothing in every clean checkout — five silent skips in the
    0.4.7 run. A skipped tier is untested capability that still looks like a clean
    result in the tally, which is the failure mode this whole script exists to
    avoid. Building it here makes the tier either pass or fail.

    Two details are load-bearing, both learned by trying the obvious thing first:
    without `noinline` at -O2 the switch is folded away and there is no table to
    find, and the function needs a second argument so the compiler cannot
    constant-fold the result either. With them, the recovered table is
    `bound=7 entries=8`.
    """
    fixture = "/tmp/densebin"
    compiler = next((c for c in ("clang", "cc", "gcc") if shutil.which(c)), None)
    if compiler is None:
        return None
    source = Path("/tmp/dense_switch_fixture.c")
    try:
        source.write_text(_DENSE_SWITCH_SOURCE)
        built = subprocess.run([compiler, "-O2", "-o", fixture, str(source)],
                               capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    if built.returncode != 0 or not Path(fixture).exists():
        return None
    return fixture


def tier14_dispatch(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    fixture = dense_switch_fixture()
    if fixture is None:
        return "skip", "no C compiler available to build the dense-switch fixture"
    payload = hub("dispatch-native", fixture)
    tables = payload.get("tables") or []
    return bool(tables) and tables[0].get("bound") == 7, \
        f"tables={len(tables)} bound={tables[0].get('bound') if tables else None}"


def tier15_resilience(path: str, expected: str):
    if expected == "pdb":
        return "skip", "binary tiers do not apply to a symbol file"
    directory = str(Path(path).parent)
    peers = sorted(p for p in Path(directory).glob("*") if p.is_file())[:20]
    failures = []
    unreadable = 0
    for peer in peers:
        if not os.access(peer, os.R_OK):
            unreadable += 1
            continue
        payload = hub("overview", str(peer), timeout=120)
        if not payload.get("ok"):
            failures.append(f"{peer.name}: {(payload.get('error') or '')[:60]}")
    return not failures, f"checked={len(peers) - unreadable} failures={len(failures)}" + \
        (f" unreadable={unreadable}" if unreadable else "")


TIERS = [
    ("T1 format identification", tier1_format),
    ("T2 arch and bitness", tier2_arch),
    ("T3 entry or first function", tier3_entry),
    ("T4 section inventory", tier4_sections),
    ("T5 symbol recovery", tier5_names),
    ("T6 instruction decode", tier6_disasm),
    ("T7 cross references", tier7_xrefs),
    ("T8 imports and exports", tier8_imports),
    ("T9 string extraction", tier9_strings),
    ("T10 entropy agreement", tier10_entropy),
    ("T11 call graph", tier11_callgraph),
    ("T12 structured decompilation", tier12_decompile),
    ("T13 type information", tier13_types),
    ("T14 dispatch tables", tier14_dispatch),
    ("T15 corpus resilience", tier15_resilience),
]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reps", type=int, default=5)
    parser.add_argument("--json", default="")
    parser.add_argument("--tiers", default="", help="comma separated tier numbers")
    args = parser.parse_args()
    if not HUB.is_file():
        print(f"hub binary missing: {HUB}", file=sys.stderr)
        return 2

    wanted = {int(t) for t in args.tiers.split(",") if t.strip()} if args.tiers else None
    rows = []
    for number, (name, function) in enumerate(TIERS, 1):
        if wanted and number not in wanted:
            continue
        for fmt, paths in CORPUS.items():
            # A symbol file only answers the type tier; running it through the binary
            # tiers produced 28 "skip" rows that said nothing about either.
            if fmt == "pdb" and number != 13:
                continue
            if fmt != "pdb" and number == 13 and not any(
                    Path(p).with_suffix(".pdb").exists() for p in available(paths)):
                continue
            for path in available(paths):
                outcomes, times = [], []
                for _ in range(args.reps):
                    started = time.time()
                    try:
                        verdict, detail = function(path, fmt)
                    except subprocess.TimeoutExpired:
                        verdict, detail = False, "timeout"
                    except Exception as error:  # a benchmark must not die on one fixture
                        verdict, detail = False, f"{type(error).__name__}: {error}"
                    times.append(time.time() - started)
                    outcomes.append(verdict)
                passed = outcomes.count(True)
                skipped = outcomes.count("skip")
                median = statistics.median(times)
                status = "PASS" if passed == len(outcomes) else ("SKIP" if skipped == len(outcomes) else "FAIL")
                rows.append({"tier": number, "name": name, "format": fmt,
                             "path": Path(path).name, "status": status,
                             "passed": passed, "runs": len(outcomes),
                             "median_s": round(median, 3), "detail": detail})
                print(f"{number:2} {fmt:6} {Path(path).name[:28]:28} {status:4} "
                      f"{passed}/{len(outcomes)} {median:6.3f}s  {detail[:70]}")

    summary = {}
    for row in rows:
        key = (row["format"], row["status"])
        summary[key] = summary.get(key, 0) + 1
    print("\nper-format tally:")
    for fmt in CORPUS:
        counts = {s: summary.get((fmt, s), 0) for s in ("PASS", "FAIL", "SKIP")}
        print(f"  {fmt:6} pass={counts['PASS']:3} fail={counts['FAIL']:3} skip={counts['SKIP']:3}")
    if args.json:
        Path(args.json).write_text(json.dumps({"reps": args.reps, "rows": rows}, indent=2))
        print(f"\nwrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
